// Keeps the licence ledger in sync for project-generated assets (assets.md §5):
// public/assets/credits.json (shipped) and the table in art/LICENSES.md (human).
// External assets are added by hand / by importers and are left untouched.
import { readFileSync, writeFileSync } from 'node:fs'
import { basename, join } from 'node:path'
import { ASSETS_DIR, loadTargets, MODELS_DIR, rel, ROOT, sha256, walk } from './lib/assets.mjs'

const AUTHOR = 'AI Office project'
const targets = new Map(loadTargets().map((t) => [t.name, t]))
const generated = []
const palette = join(ASSETS_DIR, 'textures', 'palette.png')
generated.push({ file: palette, title: 'Palette texture', source: 'art/blender/gen_palette.py' })
for (const file of walk(MODELS_DIR).filter((f) => f.endsWith('.glb'))) {
  const t = targets.get(basename(file, '.glb'))
  if (t && t.source === 'generated') generated.push({ file, title: t.name, source: t.script })
}
const genPaths = new Set(generated.map((g) => rel(g.file).replace(/^public\//, '')))

const creditsPath = join(ASSETS_DIR, 'credits.json')
const credits = JSON.parse(readFileSync(creditsPath, 'utf8'))
const kept = credits.assets.filter((a) => !genPaths.has(a.path) && a.license !== 'own-CC0')
const own = generated.map((g) => ({
  path: rel(g.file).replace(/^public\//, ''), title: g.title, author: AUTHOR,
  source: g.source, license: 'own-CC0', modified: false, sha256: sha256(g.file),
}))
const all = [...kept, ...own]
writeFileSync(creditsPath, '{\n  "assets": [\n' + all.map((a) => '    ' + JSON.stringify(a)).join(',\n') + '\n  ]\n}\n')

const licPath = join(ROOT, 'art', 'LICENSES.md')
const lines = readFileSync(licPath, 'utf8').split('\n')
const isOwnRow = (l) => l.startsWith('| `public/assets/') && l.includes(`| ${AUTHOR} `)
const outLines = lines.filter((l) => !isOwnRow(l))
let last = outLines.findLastIndex((l) => l.startsWith('| '))
const rows = own.map((a) => `| \`public/${a.path}\` | ${a.title} | ${AUTHOR} (generated by \`${a.source}\`) | own work, released CC0 1.0 | \`${a.sha256}\` |`)
outLines.splice(last + 1, 0, ...rows)
writeFileSync(licPath, outLines.join('\n'))
console.log(`credits: ${kept.length} external + ${own.length} generated`)
